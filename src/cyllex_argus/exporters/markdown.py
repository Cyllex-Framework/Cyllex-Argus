"""Human-readable profile: summary, facts table and citations.

Names, titles, quotes and locations come from untrusted documents, so every such field is emitted
through `_md` (one inert line, all Markdown markup escaped) and only plain http(s) locations become
links. Nothing here can turn document text into a heading, a table row or a remote image.
"""

from __future__ import annotations

import re
from datetime import date

from cyllex_argus.knowledge.models import TLP, TLP_ORDER, DocumentCoverage, Polarity
from cyllex_argus.knowledge.profile import FactView, Profile

_MARKUP = re.compile(r"([\\`*_\[\]<>!#|])")
_HTTP_URL = re.compile(r"https?://[^\s<>]+")


def _md(text: object) -> str:
    """Untrusted text as a single line of inert Markdown."""
    return _MARKUP.sub(r"\\\1", " ".join(str(text).split()))


def _coverage_lines(coverage: DocumentCoverage) -> list[str]:
    """The evidence base, stated before the findings.

    A profile built from 25 of 40 documents looks exactly like a profile built from 25 of 25. The
    reader cannot tell them apart from the facts, so the document has to tell them — and has to
    say what the gap does and does not mean, because "we found no evidence" and "we could not
    read the sources" are different claims and only the first is a finding.
    """
    if coverage.collected == 0:
        return []
    lines = [
        "## Evidence base", "",
        f"Built from **{coverage.validated} of {coverage.collected}** documents collected for "
        f"this threat.",
    ]
    detail = []
    if coverage.unreadable:
        detail.append(f"{coverage.unreadable} could not be retrieved or parsed")
    if coverage.off_topic:
        detail.append(f"{coverage.off_topic} were ruled off-topic at triage")
    if detail:
        lines.append("")
        lines.append(_sentence(detail) + ".")
    if coverage.unreadable:
        lines += [
            "",
            "The unread documents contributed no facts to this profile. A finding absent below "
            "may be absent from the reporting, or present only in a document this collection "
            "could not read; this profile cannot tell the two apart.",
        ]
    return lines + [""]


def _sentence(parts: list[str]) -> str:
    """'a', 'a and b', 'a, b and c' — with the first letter capitalised."""
    if len(parts) == 1:
        joined = parts[0]
    else:
        joined = ", ".join(parts[:-1]) + " and " + parts[-1]
    return joined[0].upper() + joined[1:]


def render_markdown(
    profile: Profile, summary: str | None, generated_on: date, *,
    summary_unavailable: str | None = None,
    tlp_cap: TLP | None = None,
    coverage: DocumentCoverage | None = None,
) -> str:
    """`summary_unavailable` is why a requested summary is missing: the file then says so in its own text.

    When `tlp_cap` is set, citations whose publisher has a TLP strictly above the cap are stripped,
    and facts left with zero citations are omitted. Publishers with no TLP label are not filtered
    — the operator decides separately how to handle unclassified sources.

    `coverage` is the evidence base this profile rests on (`SQLiteStore.coverage_for_entity`).
    Passing it is strongly preferred: without it the file makes no statement about what it could
    not read, which is the one thing a reader cannot infer from the findings.
    """
    if tlp_cap is not None:
        profile = _apply_tlp_cap(profile, tlp_cap)
    entity = profile.entity
    tlp_banner = f" · tlp:{tlp_cap.value}" if tlp_cap is not None else ""
    lines = [
        f"# {_md(entity.name)}", "",
        f"*{entity.stix_type} · generated by Cyllex Argus on {generated_on.isoformat()}{tlp_banner}*",
        "",
    ]
    if profile.aliases:
        lines += [f"**Aliases:** {', '.join(_md(alias) for alias in profile.aliases)}", ""]
    if coverage is not None:
        lines += _coverage_lines(coverage)
    if summary:
        lines += ["## Executive summary", "", _md(summary), ""]
    elif summary_unavailable is not None:
        lines += ["## Executive summary", "", f"_Summary unavailable: {_md(summary_unavailable)}_", ""]
    lines += ["## Assessed facts", ""]
    if not profile.facts:
        lines += ["No assessments yet.", ""]
        return "\n".join(lines).rstrip() + "\n"
    lines += [
        "| # | Subject | Relation | Object | Status | Confidence | Admiralty | Seen | Sources |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for index, fact in enumerate(profile.facts, start=1):
        seen = f"{fact.first_seen or '?'} .. {fact.last_seen or '?'}" if fact.first_seen or fact.last_seen else "-"
        lines.append(
            f"| {index} | {_md(fact.subject.label)} | {fact.predicate} | {_md(fact.object.label)} | "
            f"{fact.status.value} | {fact.confidence} | {fact.admiralty} | {seen} | {fact.source_count} |"
        )
    lines += ["", "## Citations", ""]
    for index, fact in enumerate(profile.facts, start=1):
        lines += [f"**[{index}] {_md(fact.subject.label)} {fact.predicate} {_md(fact.object.label)}**", ""]
        for citation in fact.citations:
            stance = "refutes" if citation.polarity is Polarity.REFUTES else "supports"
            if citation.location and _HTTP_URL.fullmatch(citation.location):
                where = f" <{citation.location}>"
            elif citation.location:
                where = f" ({_md(citation.location)})"
            else:
                where = ""
            lines.append(
                f"- {_md(citation.publisher)}, *{_md(citation.document_title)}* "
                f"({citation.published_at or 'undated'}, {stance}){where}: \"{_md(citation.quote)}\""
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _apply_tlp_cap(profile: Profile, cap: TLP) -> Profile:
    """Drop citations whose publisher TLP exceeds the cap; drop facts left with no evidence."""
    cap_rank = TLP_ORDER[cap.value]
    kept_facts: list[FactView] = []
    for fact in profile.facts:
        kept_cites = [
            c for c in fact.citations
            if c.publisher_tlp is None or TLP_ORDER.get(c.publisher_tlp, -1) <= cap_rank
        ]
        if kept_cites:
            kept_facts.append(fact.model_copy(update={"citations": kept_cites}))
    return profile.model_copy(update={"facts": kept_facts})
